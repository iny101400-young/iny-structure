    if "--분류" in sys.argv:
        자리 = sys.argv.index("--분류")
        if 자리 + 1 < len(sys.argv):
            규칙길 = os.path.expanduser(sys.argv[자리 + 1])
    지도 = 훑기(폴더, 규칙길)
    if "--조용히" not in sys.argv:
        print(요약(지도))
