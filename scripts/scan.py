def 머리말_가르기(글):
    """첫 `---` 블록 하나만 걷어낸다.

    01 은 원본 머리말을 지우지 않고 그 위에 자기 머리말을 얹었다.
    둘째 블록까지 지우면 본문이 통째로 날아간다. 실제로 한 번 그렇게 헛돌았다.
    둘째 블록은 원본이 갖고 있던 것이라 date 같은 쓸모 있는 값이 거기 있다.
    """
    if not 글.startswith("---"):
        return {}, 글, False

    끝 = 글.find("\n---", 3)
    if 끝 == -1:
        return {}, 글, False

    머리 = 글[3:끝]
    몸 = 글[끝 + 4:].lstrip("\n")

    값 = {}
    for 줄 in 머리.splitlines():
        if ":" in 줄 and not 줄.startswith((" ", "\t", "#")):
            열쇠, _, 값1 = 줄.partition(":")
            값[열쇠.strip()] = 값1.strip()

    두겹 = 몸.startswith("---")
    return 값, 몸, 두겹


def 원본머리말_읽기(몸):
    """두 겹일 때 둘째 블록을 읽는다. 걷어내지 않고 읽기만 한다."""
    if not 몸.startswith("---"):
        return {}
    끝 = 몸.find("\n---", 3)
    if 끝 == -1:
        return {}
    값 = {}
    for 줄 in 몸[3:끝].splitlines():
        if ":" in 줄 and not 줄.startswith((" ", "\t", "#")):
            열쇠, _, 값1 = 줄.partition(":")
            값[열쇠.strip()] = 값1.strip()
    return 값


def 날짜_캐기(머리, 원본머리, 출처):
    """원본 날짜를 세 군데서 찾는다. 못 찾으면 비운다.

    ingested_at 은 절대 안 쓴다. 재료화한 날이지 자료가 만들어진 날이 아니다.
    """
    for 열쇠 in ("created", "date", "작성일", "날짜"):
        값 = 원본머리.get(열쇠) or 머리.get(열쇠)
        if 값:
            맞 = 날짜패턴[0].search(값)
            if 맞:
                return 맞.group(0)[:10].replace("_", "-").replace(".", "-"), "원본머리말"

    for 패턴 in 날짜패턴:
        맞 = 패턴.search(출처)
        if 맞:
            덩이 = 맞.group(0)
            if len(덩이) == 6 and 덩이.isdigit():          # 260812
                return f"20{덩이[:2]}-{덩이[2:4]}-{덩이[4:]}", "경로"
            정리 = re.sub(r"[_.]", "-", 덩이)
            if len(정리) == 8 and 정리.isdigit():
                정리 = f"{정리[:4]}-{정리[4:6]}-{정리[6:]}"
            return 정리, "경로"

    if 출처 and os.path.exists(출처):
        import datetime
        때 = datetime.datetime.fromtimestamp(os.path.getmtime(출처))
        return 때.strftime("%Y-%m-%d"), "원본수정시각"

    return "", ""


def 제외규칙_읽기(작업폴더):
    """제외목록.md 에서 규칙만 읽는다. 사람이 읽는 설명은 무시한다.

    첫 칸이 빼기 또는 넣기 인 행, 둘째 칸의 백틱 안이 경로다.
    넣기 가 빼기 를 이긴다.
    제외목록.md 첫 줄이 03 을 지목해 놨다. 반드시 읽는다.
    """
    길 = os.path.join(작업폴더, "제외목록.md")
    빼기, 넣기 = [], []
    if not os.path.exists(길):
        return 빼기, 넣기
    for 줄 in open(길, encoding="utf-8", errors="replace"):
        칸 = [c.strip() for c in 줄.strip().strip("|").split("|")]
        if len(칸) < 2:
            continue
        맞 = re.search(r"`([^`]+)`", 칸[1])
        if not 맞:
            continue
        조각 = NFC(맞.group(1))
        if 칸[0] == "빼기":
            빼기.append(조각)
        elif 칸[0] == "넣기":
            넣기.append(조각)
    return 빼기, 넣기


def 걸리나(길, 규칙들):
    import fnmatch
    길 = NFC(길)
    for 규칙 in 규칙들:
        if "*" in 규칙:
            if fnmatch.fnmatch(길, 규칙) or fnmatch.fnmatch(길, "*" + 규칙 + "*"):
                return True
        elif 규칙 in 길:
            return True
    return False


def 출처묶음(출처들):
    """출처 절대경로들의 공통 조상 아래 두 겹을 묶음 이름으로 쓴다.

    02 는 한 겹만 봤다. 그러면 학원 자료 수백 개가 통째로 한 묶음이 된다.
    그 안에 강사가 만든 것과 본인이 만든 것이 섞여 있다.
    한 겹 더 파야 폴더 끝의 사람 이름이 보인다.

    사람마다 자료를 둔 자리가 다르다. 경로를 스킬에 박지 않으려면 이렇게 해야 한다.
    """
    갈래 = [NFC(p).split(os.sep) for p in 출처들 if p]
    if not 갈래:
        return {}, {}
    공통 = 0
    최소 = min(len(g) for g in 갈래)
    while 공통 < 최소 - 1 and len({g[공통] for g in 갈래}) == 1:
        공통 += 1

    한겹, 두겹 = {}, {}
    for 원, 조각 in zip([p for p in 출처들 if p], 갈래):
        끝 = len(조각) - 1                       # 마지막은 파일 이름이라 뺀다
        한겹[원] = 조각[공통] if 공통 < 끝 else "(바로 위)"
        if 공통 + 1 < 끝:
            두겹[원] = os.sep.join(조각[공통:공통 + 2])
        else:
            두겹[원] = 한겹[원]
    return 한겹, 두겹


def 사람이름_뽑기(묶음2):
    """폴더 이름 끝에 붙은 사람 이름을 뽑는다.

    학원 · 부트캠프 · 사내 교육 폴더는 대개 강사 자료와 제출물이 한자리에 있다.
    맨 위 폴더 이름으로 가르면 둘이 같이 버려진다.
    폴더 끝의 사람 이름으로 갈라야 한다.

    어느 이름이 본인인지는 여기서 안 정한다. 스킬이 묶음 단위로 묻는다.
    """
    if not 묶음2:
        return ""
    맞 = 이름끝패턴.search(묶음2.split(os.sep)[-1])
    return 맞.group(1) if 맞 else ""


def 개인정보_훑기(몸):
    """걸린 종류만 돌려준다. 값은 절대 안 돌려준다.

    03 은 02 보다 한 칸 세다. 02 는 근거를 뽑을 뿐이지만 03 은 위키 문서를 새로 쓴다.
    그 문서가 06 에서 사이트가 되고 07 이 발행한다.
    위키에 한 번 들어간 연락처는 그대로 공개된다.
    """
    걸린것 = []
    for 이름, 패턴 in 개인정보패턴:
        if 패턴.search(몸):
            걸린것.append(이름)
    return 걸린것


def 분류규칙_읽기(길):
    """스킬이 쓴 분류 규칙을 읽는다.

    탭으로 나눈 네 칸이다.  갈래 / 값 / 분류 / 위키
    갈래는 길 · 이름끝 · 묶음2 · 묶음 넷 중 하나다.
    # 로 시작하는 줄과 빈 줄은 건너뛴다.

        묶음	{묶음 이름}	글감
        묶음2	{묶음 이름}/{하위 폴더}	글감
        이름끝	{남의 이름}	안씀:남의것
        길	raw/notes/{파일 이름}.md	글감	{위키 문서 슬러그}

    좁은 것이 넓은 것을 이긴다.  길 > 이름끝 > 묶음2 > 묶음
    """
    규칙 = {"길": {}, "이름끝": {}, "묶음2": {}, "묶음": {}}
    if not 길 or not os.path.exists(길):
        return 규칙
    for 줄 in open(길, encoding="utf-8", errors="replace"):
        줄 = 줄.rstrip("\n")
        if not 줄.strip() or 줄.lstrip().startswith("#"):
            continue
        칸 = 줄.split("\t")
        if len(칸) < 3:
            continue
        갈래, 값, 분류 = 칸[0].strip(), NFC(칸[1].strip()), 칸[2].strip()
        위키 = 칸[3].strip() if len(칸) > 3 else ""
        if 갈래 in 규칙 and 값:
            규칙[갈래][값] = (분류, 위키)
    return 규칙


def 분류_고르기(f, 규칙):
    """좁은 규칙이 넓은 규칙을 이긴다. 스크립트 자동 판정이 제일 세다."""
    if f.get("분류"):                       # 중복 · 빈 것 · 제외목록. 규칙이 못 덮는다
        return f["분류"], ""
    for 갈래, 열쇠 in (("길", f["길"]), ("이름끝", f["이름끝"]),
                       ("묶음2", f["묶음2"]), ("묶음", f["묶음"])):
        if 열쇠 and 열쇠 in 규칙[갈래]:
            return 규칙[갈래][열쇠]
    return "", ""


def 훑기(작업폴더, 분류규칙길=""):
    재료뿌리 = os.path.join(작업폴더, "raw")
    if not os.path.isdir(재료뿌리):
        print(f"재료 폴더가 없습니다: {재료뿌리}", file=sys.stderr)
        print("03 은 01 이 만든 재료를 읽는 단계입니다. 01 을 먼저 돌리셔야 합니다.",
              file=sys.stderr)
        sys.exit(1)

    빼기규칙, 넣기규칙 = 제외규칙_읽기(작업폴더)
    규칙 = 분류규칙_읽기(분류규칙길)

    파일들 = []
    제외됨 = 0

    for 뿌리, 폴더들, 이름들 in os.walk(재료뿌리):
        폴더들[:] = [d for d in 폴더들 if not d.startswith(".")]
        for 이름 in sorted(이름들):
            if not 이름.endswith(".md"):
                continue
            길 = os.path.join(뿌리, 이름)
            상대 = NFC(os.path.relpath(길, 작업폴더))

            try:
                글 = open(길, encoding="utf-8", errors="replace").read()
            except OSError:
                continue

            머리, 몸, 두겹 = 머리말_가르기(글)
            원본머리 = 원본머리말_읽기(몸) if 두겹 else {}
            출처 = NFC(머리.get("source", ""))

            if 걸리나(출처 or 상대, 빼기규칙) and not 걸리나(출처 or 상대, 넣기규칙):
                제외됨 += 1
                continue

            알맹이 = re.sub(r"\s+", "", 몸)
            글자수 = len(알맹이)
            해시 = hashlib.sha1(알맹이.encode()).hexdigest()[:12] if 글자수 else ""

            날짜, 날짜출처 = 날짜_캐기(머리, 원본머리, 출처)
            형식 = 머리.get("type", "")

            파일들.append({
                "길": 상대,
                "이름": os.path.splitext(os.path.basename(출처))[0] if 출처 else 이름[:-3],
                "형식": 형식,
                "주인": 머리.get("owner", ""),
                "개인정보표기": 머리.get("sensitive", ""),
                "가린날": 머리.get("masked_at", ""),
                "이미지설명": 머리.get("described", ""),
                "글자수": 글자수,
                "해시": 해시,
                "날짜": 날짜,
                "날짜출처": 날짜출처,
                "두겹머리말": 두겹,
                "개인정보후보": 개인정보_훑기(몸),
                "내것신호": bool(내것신호.search(os.path.basename(출처) or 이름)),
                "원본있음": bool(출처) and os.path.exists(출처),
                "분류": "",
                "위키": "",
                "_출처": 출처,
            })

    한겹, 두겹이름 = 출처묶음([f["_출처"] for f in 파일들])
    for f in 파일들:
        f["묶음"] = 한겹.get(f["_출처"], "(출처 없음)")
        f["묶음2"] = 두겹이름.get(f["_출처"], f["묶음"])
        f["이름끝"] = 사람이름_뽑기(f["묶음2"])

    # 같은 본문끼리 묶는다. 대표 하나만 세고 나머지는 개수로만 남긴다.
    해시별 = defaultdict(list)
    for f in 파일들:
        if f["해시"]:
            해시별[f["해시"]].append(f)

    중복묶음 = []
    for 해시, 무리 in 해시별.items():
        if len(무리) < 2:
            continue
        무리.sort(key=lambda x: (len(x["길"]), x["길"]))
        대표 = 무리[0]["길"]
        for f in 무리[1:]:
            f["중복"] = 대표
            f["분류"] = "안씀:중복"
        중복묶음.append({
            "대표": 대표,
            "개수": len(무리),
            "글자수": 무리[0]["글자수"],
            "같은것": [x["길"] for x in 무리[1:]],
        })
    중복묶음.sort(key=lambda x: -x["개수"])

    # 사실상 빈 것. 이미지는 안 센다.
    # 형식이 image 인데 본문이 0자인 건 「안에 뭐가 있는지 아직 안 적힌 것」이지
    # 「내용이 없는 것」이 아니다. 자동으로 안 씀에 넣지 않는다.
    for f in 파일들:
        if f["분류"] or f["형식"] == "image":
            continue
        if f["글자수"] < 빈파일_기준:
            f["분류"] = "안씀:빈것"

    # 스킬이 준 규칙을 얹는다
    for f in 파일들:
        분류, 위키 = 분류_고르기(f, 규칙)
        if 분류:
            f["분류"] = 분류
        if 위키:
            f["위키"] = 위키

    고유 = [f for f in 파일들 if not f.get("중복")]
    이미지 = [f for f in 파일들 if f["형식"] == "image"]

    묶음별 = defaultdict(lambda: {"개수": 0, "글자수": 0, "형식": Counter(),
                                  "중복": 0, "빈것": 0, "이미지": 0,
                                  "이름끝": Counter(), "날짜있음": 0, "분류": Counter()})
    for f in 파일들:
        칸 = 묶음별[f["묶음"]]
        칸["개수"] += 1
        칸["형식"][f["형식"] or "미상"] += 1
        칸["분류"][f["분류"] or "안정함"] += 1
        if f["이름끝"]:
            칸["이름끝"][f["이름끝"]] += 1
        if f["형식"] == "image":
            칸["이미지"] += 1
        if f.get("중복"):
            칸["중복"] += 1
            continue
        칸["글자수"] += f["글자수"]
        if f["글자수"] < 빈파일_기준 and f["형식"] != "image":
            칸["빈것"] += 1
        if f["날짜"]:
            칸["날짜있음"] += 1

    묶음표 = sorted(
        ({"이름": 이름, "개수": v["개수"], "글자수": v["글자수"],
          "중복": v["중복"], "빈것": v["빈것"], "이미지": v["이미지"],
          "날짜있음": v["날짜있음"], "형식": dict(v["형식"]),
          "이름끝": dict(v["이름끝"]), "분류": dict(v["분류"])}
         for 이름, v in 묶음별.items()),
        key=lambda x: -x["글자수"])

    # 두 겹 묶음은 사람 이름이 붙은 것만 따로 낸다. 여기가 주인이 갈리는 자리다
    두겹표 = defaultdict(lambda: {"개수": 0, "글자수": 0, "이미지": 0, "이름끝": ""})
    for f in 파일들:
        칸 = 두겹표[f["묶음2"]]
        칸["개수"] += 1
        칸["이름끝"] = f["이름끝"]
        if f["형식"] == "image":
            칸["이미지"] += 1
        if not f.get("중복"):
            칸["글자수"] += f["글자수"]
    이름붙은묶음 = sorted(
        ({"이름": k, **v} for k, v in 두겹표.items() if v["이름끝"]),
        key=lambda x: -x["글자수"])

    분류집계 = Counter(f["분류"] or "안정함" for f in 파일들)
    분류글자 = defaultdict(int)
    for f in 파일들:
        if not f.get("중복"):
            분류글자[f["분류"] or "안정함"] += f["글자수"]

    지도 = {
        "총계": {
            "파일": len(파일들),
            "중복": len(파일들) - len(고유),
            "고유": len(고유),
            "본문글자수": sum(f["글자수"] for f in 고유),
            "빈것": sum(1 for f in 고유
                        if f["글자수"] < 빈파일_기준 and f["형식"] != "image"),
            "이미지": len(이미지),
            "제외목록으로뺌": 제외됨,
            "날짜있음": sum(1 for f in 고유 if f["날짜"]),
            "두겹머리말": sum(1 for f in 파일들 if f["두겹머리말"]),
        },
        "형식": dict(Counter(f["형식"] or "미상" for f in 파일들)),
        "묶음": 묶음표,
        "이름붙은묶음": 이름붙은묶음,
        "사람이름": dict(Counter(f["이름끝"] for f in 파일들 if f["이름끝"])),
        "중복묶음": 중복묶음[:40],
        "이미지": {
            "전체": len(이미지),
            "본문채워짐": sum(1 for f in 이미지 if f["글자수"] >= 빈파일_기준),
            "원본살아있음": sum(1 for f in 이미지 if f["원본있음"]),
            "묶음별": dict(Counter(f["묶음2"] for f in 이미지)),
            "이름붙은것": dict(Counter(f["이름끝"] for f in 이미지 if f["이름끝"])),
        },
        "되찾을후보": {
            "설명": "폴더 끝에 사람 이름이 붙어 있는데 파일 이름은 본인이 쓴 것처럼 보이는 것. "
                    "남의 이름 폴더면 스킬이 살릴지 판단하고 사람이 짚는다",
            "개수": sum(1 for f in 파일들 if f["이름끝"] and f["내것신호"]),
            "목록": [{"길": f["길"], "묶음2": f["묶음2"], "이름끝": f["이름끝"],
                      "이름": f["이름"], "글자수": f["글자수"]}
                     for f in 파일들
                     if f["이름끝"] and f["내것신호"] and not f.get("중복")][:300],
        },
        "개인정보": {
            "이미가림": [{"길": f["길"], "종류": f["개인정보표기"], "가린날": f["가린날"]}
                          for f in 파일들 if f["개인정보표기"]],
            "후보개수": sum(1 for f in 파일들 if f["개인정보후보"]),
            "후보": [{"길": f["길"], "종류": f["개인정보후보"]}
                     for f in 파일들 if f["개인정보후보"]][:200],
        },
        "분류": {
            "개수": dict(분류집계),
            "글자수": dict(분류글자),
        },
    }

    칸 = os.path.join(작업폴더, ".kb")
    os.makedirs(칸, exist_ok=True)

    with open(os.path.join(칸, "구조지도.json"), "w", encoding="utf-8") as 손:
        json.dump(지도, 손, ensure_ascii=False, indent=2)

    with open(os.path.join(칸, "분류표.tsv"), "w", encoding="utf-8") as 손:
        손.write("길\t묶음\t묶음2\t이름끝\t형식\t글자수\t날짜\t날짜출처"
                 "\t개인정보\t중복대표\t분류\t위키\t이름\n")
        for f in sorted(파일들, key=lambda x: (-x["글자수"], x["길"])):
            손.write("\t".join([
                f["길"], f["묶음"], f["묶음2"], f["이름끝"], f["형식"] or "",
                str(f["글자수"]), f["날짜"], f["날짜출처"],
                ",".join(f["개인정보후보"]) or (f["개인정보표기"] and "이미가림") or "",
                f.get("중복", ""), f["분류"], f["위키"],
                f["이름"].replace("\t", " "),
            ]) + "\n")

    return 지도


def 요약(지도):
    ㅅ = 지도["총계"]
    ㅂ = 지도["분류"]["개수"]
    줄 = [
        f"재료 {ㅅ['파일']}개 · 고유 {ㅅ['고유']}개 · 본문 {ㅅ['본문글자수']:,}자",
        f"중복 {ㅅ['중복']} · 빈 것 {ㅅ['빈것']} · 이미지 {ㅅ['이미지']}"
        f" · 두 겹 머리말 {ㅅ['두겹머리말']}",
        "",
        "분류",
    ]
    for 값 in ("글감", "근거", "보류", "안정함"):
        if 값 in ㅂ:
            줄.append(f"  {ㅂ[값]:>5}개  {값}")
    for 값, 개수 in sorted(ㅂ.items()):
        if 값.startswith("안씀"):
            줄.append(f"  {개수:>5}개  {값}")
    줄 += ["", "폴더 끝에 이름이 붙은 묶음 (여기서 주인이 갈린다)"]
    for m in 지도["이름붙은묶음"][:12]:
        줄.append(f"  {m['개수']:>4}개 {m['글자수']:>10,}자  {m['이름']}")
    줄 += ["", f"남의 이름 폴더 안인데 본인이 쓴 것 같은 파일 {지도['되찾을후보']['개수']}개",
           "  통째로 빼면 같이 날아간다. 스킬이 살릴지 판단한다."]
    줄 += ["", f"개인정보 후보 {지도['개인정보']['후보개수']}개"
              f" · 이미 가린 것 {len(지도['개인정보']['이미가림'])}개",
           "  값은 어디에도 안 적었습니다. 경로와 종류만 있습니다."]
    return "\n".join(줄)


